#!/usr/bin/env python3
"""A clean machine to a coding agent's first session in evald, by the README's own commands.

    python3 scripts/clean-machine.py --evald <static evald binary> [--claude <Claude Code binary>]

0.4.0's release bar (no Rust, no clone: install, serve, a coding agent's first trace, in three
commands or fewer), checked rather than claimed. A bare `ubuntu` container gets what a
clean machine has, a shell, curl and CA certificates, plus Claude Code, the coding agent the
README points at evald. Then, as an ordinary user in an empty home directory, it runs the
README's quick start (README.md, between `<!-- clean-machine:begin -->` and
`<!-- clean-machine:end -->`) one line at a time, as written, with two stand-ins:

* The installer is this tree's (`ops/install.sh`; `install.sh` in the public mirror), served
  from a local address, and the release it downloads is `--evald`, packaged the way the release
  workflow packages it (`evald-x86_64-unknown-linux-musl.tar.gz` and `SHA256SUMS`, found through
  `EVALD_DOWNLOAD_BASE`). The rest of the install is the real one: the checksum check, the
  install directory, the PATH.
* `claude`, an interactive session in the README, is `claude -p "<question>"`. Its model calls
  go to examples/recipes/stub_provider.py: no key, no network.

A shell carries on past a line that failed (`eval "$(evald connect …)"` succeeds when `evald`
is not found, and `curl … | sh` when the download 404s), so after each line the harness checks
what that line was for: evald on PATH, the server answering, Claude Code's telemetry switched
on. Then it reads the sessions the way the README's last line does, and requires one with a
model call, its model, tokens and cost. The quick start must stay at three commands or fewer
before the agent runs.

Needs docker and python3. The Claude Code binary is the one the claude-agent-sdk recipe pins
(examples/recipes/claude-agent-sdk/requirements.txt), unless --claude names one.
"""
import argparse
import functools
import glob
import hashlib
import http.server
import json
import os
import shlex
import shutil
import socket
import stat
import subprocess
import sys
import tarfile
import tempfile
import threading
import time
import zipfile

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
INSTALL_URL = "https://raw.githubusercontent.com/lucheeseng827/evald/main/install.sh"
ASSET = "evald-x86_64-unknown-linux-musl.tar.gz"
BEGIN, END = "<!-- clean-machine:begin -->", "<!-- clean-machine:end -->"
MAX_SETUP = 3
# The stub provider answers every question with the weather in Paris.
PROMPT = "What is the weather in Paris?"
PROXY_VARS = ("http_proxy", "https_proxy", "no_proxy", "HTTP_PROXY", "HTTPS_PROXY", "NO_PROXY")


def die(msg):
    sys.exit(f"clean-machine: {msg}")


def first_word(line):
    words = shlex.split(line, comments=True)
    return words[0] if words else ""


def quickstart(readme):
    """The quick start's command lines, as written, split into setup / agent / read-back."""
    text = open(readme, encoding="utf-8").read()
    if text.count(BEGIN) != 1 or text.count(END) != 1:
        die(f"{readme} must mark its quick start once with {BEGIN} … {END}")
    block = text.split(BEGIN, 1)[1].split(END, 1)[0]
    lines, fenced = [], False
    for raw in block.splitlines():
        if raw.strip().startswith("```"):
            fenced = not fenced
        elif fenced and raw.strip() and not raw.lstrip().startswith("#"):
            lines.append(raw.rstrip())
    agent = [i for i, line in enumerate(lines) if first_word(line) == "claude"]
    if len(agent) != 1:
        die(f"the quick start must run the agent (`claude`) on exactly one line: {lines}")
    setup, after = lines[: agent[0]], lines[agent[0] + 1 :]
    if not 1 <= len(setup) <= MAX_SETUP:
        die(f"the quick start takes {len(setup)} commands before the agent runs, "
            f"more than {MAX_SETUP}: {setup}")
    if block.count(INSTALL_URL) != 1 or INSTALL_URL not in setup[0]:
        die(f"the quick start's first line must be the one install line, from {INSTALL_URL}")
    if len(after) != 1 or "/v1/sessions" not in after[0]:
        die(f"the quick start must end with one line that reads /v1/sessions: {after}")
    return setup, after[0]


def user_script(setup, readback, installer_url):
    """The quick start for the container's user: each README line, then a check of what it did."""
    out = [
        "#!/bin/bash",
        "# Generated by scripts/clean-machine.py from README.md: each line as the README has it,",
        "# then a check of what that line was for (a shell carries on past a line that failed).",
        "# shellcheck disable=SC2016  # `show` prints each README line as written, unexpanded",
        "set -u",
        'cd "$HOME" || exit 1',
        "fail() { printf 'clean-machine: %s\\n' \"$*\" >&2; exit 1; }",
        "show() { printf '\\n$ %s\\n' \"$1\"; }",
    ]
    for i, line in enumerate(setup):
        out.append(f"show {shlex.quote(line)}")
        out.append(line.replace(INSTALL_URL, installer_url))
        out.append('rc=$?; [ "$rc" = 0 ] || fail "that line exited $rc"')
        if i == 0:
            out.append('command -v evald >/dev/null || fail "after the install line, evald is '
                       'not on PATH ($PATH)"')
        elif "evald serve" in line:
            out.append("up=0; for _ in $(seq 60); do if curl -fsS -o /dev/null "
                       "http://127.0.0.1:4318/healthz 2>/dev/null; then up=1; break; fi; "
                       "sleep 0.5; done")
            out.append('[ "$up" = 1 ] || fail "evald serve did not answer on :4318 within 30 s"')
        elif "evald connect" in line:
            out.append('[ "${CLAUDE_CODE_ENABLE_TELEMETRY:-}" = 1 ] || fail "evald connect '
                       'did not switch on Claude Code\'s telemetry"')
    out.append(f"show {shlex.quote('claude -p ' + shlex.quote(PROMPT))}")
    out.append(f"claude -p {shlex.quote(PROMPT)} </dev/null || fail \"claude exited $?\"")
    # Claude Code exports its last events as it exits; read them back the README's way until
    # they are in, rather than once after a guessed sleep.
    out.append(f"show {shlex.quote(readback)}")
    out.append("for _ in $(seq 30); do")
    out.append("{")
    out.append(readback)
    out.append("} > /out/sessions.json")
    out.append('  grep -q \'"llm_calls":[1-9]\' /out/sessions.json && break; sleep 1')
    out.append("done")
    out.append("cat /out/sessions.json; echo")
    return "\n".join(out) + "\n"


ROOT_SCRIPT = """#!/bin/bash
# Inside the bare container, as root: give it a clean machine's baseline, then hand over to the
# user, who runs the README.
set -euo pipefail
for tool in cargo rustc rustup git evald; do
    if command -v "$tool" >/dev/null; then echo "clean-machine: $tool is already here" >&2; exit 1; fi
done
if ! command -v curl >/dev/null; then
    export DEBIAN_FRONTEND=noninteractive
    apt-get update -qq >/dev/null
    apt-get install -y -qq --no-install-recommends curl ca-certificates >/dev/null
fi
# The coding agent, installed the way its user would have.
install -m 0755 /work/agent/claude /usr/local/bin/claude
claude --version
# An ordinary user (the image's own), with its stock home directory and PATH.
exec runuser -u ubuntu -- bash /work/as-user.sh
"""


class Files(http.server.SimpleHTTPRequestHandler):
    def log_message(self, *_):
        pass


def free_port():
    with socket.socket() as s:
        s.bind(("127.0.0.1", 0))
        return s.getsockname()[1]


def wait_port(port, proc, log):
    for _ in range(100):
        if proc.poll() is not None:
            die(f"the stub provider exited: {open(log).read()}")
        with socket.socket() as s:
            if s.connect_ex(("127.0.0.1", port)) == 0:
                return
        time.sleep(0.1)
    die(f"nothing listens on :{port}: {open(log).read()}")


def package(evald, dist):
    """The release archive and SHA256SUMS, as ops/release.yml makes them."""
    os.makedirs(dist)
    with tarfile.open(os.path.join(dist, ASSET), "w:gz") as t:
        info = t.gettarinfo(evald, arcname="evald")
        info.mode = 0o755
        with open(evald, "rb") as f:
            t.addfile(info, f)
    h = hashlib.sha256()
    with open(os.path.join(dist, ASSET), "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    with open(os.path.join(dist, "SHA256SUMS"), "w") as f:
        f.write(f"{h.hexdigest()}  {ASSET}\n")


def claude_from_wheel(work):
    req = os.path.join(HERE, "examples/recipes/claude-agent-sdk/requirements.txt")
    wheels = os.path.join(work, "wheels")
    subprocess.run([sys.executable, "-m", "pip", "download", "--quiet", "--no-deps",
                    "--only-binary=:all:", "-d", wheels, "-r", req], check=True)
    (whl,) = glob.glob(os.path.join(wheels, "claude_agent_sdk-*.whl"))
    with zipfile.ZipFile(whl) as z:
        member = "claude_agent_sdk/_bundled/claude"
        z.extract(member, work)
    return os.path.join(work, member)


def check(sessions):
    if not isinstance(sessions, list) or not sessions:
        die(f"no session: {sessions}")
    s = sessions[0]
    tokens = s.get("tokens") or {}
    problems = [
        what
        for what, ok in [
            ("a model call", s.get("llm_calls", 0) >= 1),
            ("no failed model call", s.get("llm_errors", 1) == 0),
            ("the model", bool(s.get("models"))),
            ("input tokens", tokens.get("prompt", 0) > 0),
            ("output tokens", tokens.get("completion", 0) > 0),
            ("a cost", (s.get("cost_usd") or 0) > 0),
        ]
        if not ok
    ]
    if problems:
        die(f"the session lacks {', '.join(problems)}: {json.dumps(s)}")
    return s


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--evald", required=True, help="the evald binary to install (static musl)")
    ap.add_argument("--claude", help="a Claude Code binary (default: the recipe's pinned one)")
    ap.add_argument("--image", default="ubuntu:24.04")
    ap.add_argument("--readme", default=os.path.join(HERE, "README.md"))
    a = ap.parse_args()

    installer = next((p for p in (os.path.join(HERE, "ops/install.sh"),
                                  os.path.join(HERE, "install.sh")) if os.path.isfile(p)), None)
    if not installer:
        die("no install.sh (ops/install.sh in the monorepo, install.sh in the mirror)")
    setup, readback = quickstart(a.readme)

    work = tempfile.mkdtemp(prefix="clean-machine-")
    procs = []
    try:
        www = os.path.join(work, "www")
        os.makedirs(www)
        shutil.copy(installer, os.path.join(www, "install.sh"))
        package(a.evald, os.path.join(www, "dist"))
        os.makedirs(os.path.join(work, "agent"))
        shutil.copy(a.claude or claude_from_wheel(work), os.path.join(work, "agent", "claude"))
        out = os.path.join(work, "out")
        os.makedirs(out)
        os.chmod(out, 0o777)  # the container's user writes the read-back here

        www_port, stub_port = free_port(), free_port()
        handler = functools.partial(Files, directory=www)
        srv = http.server.ThreadingHTTPServer(("127.0.0.1", www_port), handler)
        threading.Thread(target=srv.serve_forever, daemon=True).start()
        stub_log = os.path.join(work, "stub.log")
        with open(stub_log, "w") as log:
            stub = subprocess.Popen([sys.executable, os.path.join(HERE, "examples/recipes/stub_provider.py"),
                                     "--port", str(stub_port)], stderr=log, stdout=log)
        procs.append(stub)
        wait_port(stub_port, stub, stub_log)

        with open(os.path.join(work, "as-user.sh"), "w") as f:
            f.write(user_script(setup, readback, f"http://127.0.0.1:{www_port}/install.sh"))
        with open(os.path.join(work, "prep.sh"), "w") as f:
            f.write(ROOT_SCRIPT)
        for name in ("as-user.sh", "prep.sh"):
            os.chmod(os.path.join(work, name), 0o755)
        os.chmod(work, os.stat(work).st_mode | stat.S_IRGRP | stat.S_IXGRP | stat.S_IROTH | stat.S_IXOTH)

        env = {
            "EVALD_DOWNLOAD_BASE": f"http://127.0.0.1:{www_port}/dist",
            "ANTHROPIC_BASE_URL": f"http://127.0.0.1:{stub_port}",
            "ANTHROPIC_API_KEY": "stub",
            # Nothing but the model calls and the telemetry leaves Claude Code.
            "CLAUDE_CODE_DISABLE_NONESSENTIAL_TRAFFIC": "1",
            **{k: os.environ[k] for k in PROXY_VARS if k in os.environ},
        }
        cmd = ["docker", "run", "--rm", "--network", "host",
               "-v", f"{work}:/work:ro", "-v", f"{out}:/out"]
        for k, v in env.items():
            cmd += ["-e", f"{k}={v}"]
        cmd += [a.image, "bash", "/work/prep.sh"]
        print(f"clean-machine: {a.image}, the README's {len(setup)} commands, then Claude Code",
              flush=True)
        t0 = time.monotonic()
        rc = subprocess.run(cmd, timeout=900, check=False).returncode
        took = time.monotonic() - t0
        if rc != 0:
            die(f"the quick start failed in the container (exit {rc}); stub log:\n"
                f"{open(stub_log).read()[-2000:]}")
        s = check(json.load(open(os.path.join(out, "sessions.json"))))
        print(f"\nclean-machine: ok in {took:.0f} s: session {s['session_id']}, "
              f"{s['llm_calls']} model call(s) to {', '.join(s['models'])}, "
              f"{s['tokens'].get('total', 0)} tokens, ${s['cost_usd']:.6f}")
    finally:
        for p in procs:
            p.terminate()
        shutil.rmtree(work, ignore_errors=True)


if __name__ == "__main__":
    main()
